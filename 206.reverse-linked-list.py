# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution:
    def reverseList(self, head: ListNode | None) -> ListNode | None:

        # Steps:
        # Iterate through
        # Keep a pointer to the previous node
        # and the next node

        if head is None:
            return None

        curr = None

        while head is not None:
            nxt = head.next
            head.next = curr
            curr = head
            head = nxt

        return curr



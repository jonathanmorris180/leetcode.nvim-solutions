# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution:
    def mergeTwoLists(
        self, list1: ListNode | None, list2: ListNode | None
    ) -> ListNode | None:

        # The way to do this in O(1) memory is to iterate through with two pointers to the current node in each list
        # On each iteration, we can check which one is greater and update the final result accordingly

        res = ListNode()
        curr = res

        while list1 or list2:
            if not list1 and list2:
                curr.next = list2
                break
            elif not list2 and list1:
                curr.next = list1
                break

            if list1.val < list2.val:
                curr.next = list1
                list1 = list1.next
            else:
                curr.next = list2
                list2 = list2.next
            curr = curr.next

        return res.next


